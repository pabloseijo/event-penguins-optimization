#!/usr/bin/env python3
"""Select a linear QFL scorer with cross-fit THUMOS14 candidates."""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any, Dict, List, Mapping, Optional, Sequence, Tuple

import numpy as np
import torch
import torch.nn.functional as F

from eval_actionformer_transfer_cv import (
    apply_classwise_ecdf,
    evaluate_variant,
    fit_classwise_ecdf,
    load_all_folds,
    percentile_rank,
    summarize,
    write_csv,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--actionformer-root", type=Path, required=True)
    parser.add_argument("--prepared-root", type=Path, required=True)
    parser.add_argument("--annotation-root", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--folds", type=int, default=5)
    parser.add_argument("--steps", type=int, default=500)
    parser.add_argument("--batch-size", type=int, default=65536)
    parser.add_argument("--topk-per-class-video", type=int, default=250)
    parser.add_argument("--learning-rate", type=float, default=0.03)
    parser.add_argument("--device", default="cuda")
    parser.add_argument("--seed", type=int, default=1234567891)
    parser.add_argument("--reuse-models", action="store_true")
    return parser.parse_args()


def build_protocol_audit(folds: int) -> Dict[str, Any]:
    return {
        "use": "model and recipe selection only",
        "meta_cv_fully_nested": False,
        "outer_folds": folds,
        "reason": (
            "For outer fold f, meta-training candidates from fold j were "
            "generated by a base model trained on all folds except j, which "
            "includes f. An unbiased stacked-performance estimate requires "
            "inner OOF base predictions inside every outer fold."
        ),
        "required_for_unbiased_meta_cv": (
            f"{folds} outer folds x {folds - 1} inner base-model fits"
        ),
        "final_test_implication": (
            "None: fitting the final meta-model on global OOF predictions "
            "and evaluating once on untouched test data is valid stacking."
        ),
    }


def video_class_ranks(
    videos: Sequence[Mapping[str, np.ndarray]],
) -> List[np.ndarray]:
    ranks = []
    for video in videos:
        output = np.zeros(len(video["scores"]), dtype=np.float32)
        for label in np.unique(video["labels"]):
            indices = np.flatnonzero(video["labels"] == label)
            output[indices] = percentile_rank(video["scores"][indices])
        ranks.append(output)
    return ranks


def build_design(
    videos: Sequence[Mapping[str, np.ndarray]],
    num_classes: int,
    global_rank_references: Optional[Sequence[np.ndarray]] = None,
) -> List[np.ndarray]:
    raw_scores = [video["scores"] for video in videos]
    if global_rank_references is None:
        global_rank_references = fit_classwise_ecdf(
            videos, raw_scores, num_classes
        )
    global_ranks = apply_classwise_ecdf(
        videos, raw_scores, global_rank_references
    )
    local_ranks = video_class_ranks(videos)
    designs = []
    for video, global_rank, local_rank in zip(
        videos, global_ranks, local_ranks
    ):
        one_hot = np.eye(num_classes, dtype=np.float32)[video["labels"]]
        designs.append(
            np.column_stack(
                (
                    video["features"],
                    global_rank,
                    local_rank,
                    one_hot,
                )
            ).astype(np.float32)
        )
    return designs


def select_training_indices(
    video: Mapping[str, np.ndarray],
    topk_per_class: int,
) -> np.ndarray:
    selected = [np.flatnonzero(video["target_tiou"] > 0.1)]
    for label in np.unique(video["labels"]):
        indices = np.flatnonzero(video["labels"] == label)
        order = np.argsort(video["scores"][indices])[::-1]
        selected.append(indices[order[:topk_per_class]])
    return np.unique(np.concatenate(selected))


def weighted_mean_std(
    features: np.ndarray, weights: np.ndarray
) -> Tuple[np.ndarray, np.ndarray]:
    normalized = weights / weights.sum()
    mean = np.sum(features * normalized[:, None], axis=0)
    variance = np.sum(
        np.square(features - mean) * normalized[:, None], axis=0
    )
    return (
        mean.astype(np.float32),
        np.sqrt(np.maximum(variance, 1e-8)).astype(np.float32),
    )


def collect_training_data(
    videos: Sequence[Mapping[str, np.ndarray]],
    designs: Sequence[np.ndarray],
    topk_per_class: int,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    features = []
    targets = []
    weights = []
    for video, design in zip(videos, designs):
        indices = select_training_indices(video, topk_per_class)
        features.append(design[indices])
        targets.append(video["target_tiou"][indices].astype(np.float32))
        weights.append(
            np.full(len(indices), 1.0 / len(indices), dtype=np.float32)
        )
    return (
        np.concatenate(features),
        np.concatenate(targets),
        np.concatenate(weights),
    )


def fit_qfl(
    features: np.ndarray,
    targets: np.ndarray,
    weights: np.ndarray,
    *,
    steps: int,
    batch_size: int,
    learning_rate: float,
    device: torch.device,
    seed: int,
) -> Dict[str, np.ndarray | float]:
    mean, std = weighted_mean_std(features, weights)
    normalized = ((features - mean) / std).astype(np.float32)
    inputs = torch.from_numpy(normalized)
    target_tensor = torch.from_numpy(targets.astype(np.float32))
    weight_tensor = torch.from_numpy(weights.astype(np.float32))
    model = torch.nn.Linear(features.shape[1], 1).to(device)
    torch.nn.init.zeros_(model.weight)
    torch.nn.init.zeros_(model.bias)
    optimizer = torch.optim.AdamW(
        model.parameters(), lr=learning_rate, weight_decay=1e-3
    )
    generator = np.random.default_rng(seed)
    for _ in range(steps):
        indices = generator.integers(
            0,
            len(features),
            size=min(batch_size, len(features)),
        )
        batch_inputs = inputs[indices].to(device)
        batch_targets = target_tensor[indices].to(device)
        batch_weights = weight_tensor[indices].to(device)
        optimizer.zero_grad(set_to_none=True)
        logits = model(batch_inputs).squeeze(1)
        probabilities = logits.sigmoid()
        loss = F.binary_cross_entropy_with_logits(
            logits, batch_targets, reduction="none"
        ) * torch.square(batch_targets - probabilities)
        loss = (loss * batch_weights).sum() / batch_weights.sum()
        loss.backward()
        optimizer.step()
    return {
        "mean": mean,
        "std": std,
        "weight": model.weight.detach().cpu().numpy().reshape(-1),
        "bias": float(model.bias.detach().cpu()),
    }


def predict_qfl(
    designs: Sequence[np.ndarray],
    model: Mapping[str, np.ndarray | float],
) -> List[np.ndarray]:
    mean = np.asarray(model["mean"])
    std = np.asarray(model["std"])
    weight = np.asarray(model["weight"])
    bias = float(model["bias"])
    return [
        (((design - mean) / std) @ weight + bias).astype(np.float32)
        for design in designs
    ]


def geometric_quality_scores(
    videos: Sequence[Mapping[str, np.ndarray]],
    quality_logits: Sequence[np.ndarray],
) -> List[np.ndarray]:
    return [
        np.sqrt(
            np.maximum(
                video["scores"]
                * (1.0 / (1.0 + np.exp(-logits))),
                0.0,
            )
        ).astype(np.float32)
        for video, logits in zip(videos, quality_logits)
    ]


def main() -> None:
    args = parse_args()
    actionformer_root = args.actionformer_root.expanduser().resolve()
    sys.path.insert(0, str(actionformer_root))
    os.chdir(actionformer_root)
    from libs.utils import ANETdetection, batched_nms
    from libs.utils.nms import seg_voting

    all_folds = load_all_folds(args.prepared_root, args.folds)
    num_classes = int(
        max(
            int(video["labels"].max())
            for fold in all_folds
            for video in fold
        )
        + 1
    )
    rows = []
    model_dir = args.output_dir / "models"
    model_dir.mkdir(parents=True, exist_ok=True)
    for fold, validation_videos in enumerate(all_folds):
        training_videos = [
            video
            for other_fold, videos in enumerate(all_folds)
            if other_fold != fold
            for video in videos
        ]
        raw_rank_references = fit_classwise_ecdf(
            training_videos,
            [video["scores"] for video in training_videos],
            num_classes,
        )
        training_designs = build_design(
            training_videos, num_classes, raw_rank_references
        )
        validation_designs = build_design(
            validation_videos, num_classes, raw_rank_references
        )
        model_path = model_dir / f"fold_{fold}.npz"
        if args.reuse_models and model_path.exists():
            with np.load(model_path) as stored_model:
                model = {
                    key: stored_model[key]
                    for key in stored_model.files
                }
        else:
            features, targets, weights = collect_training_data(
                training_videos,
                training_designs,
                args.topk_per_class_video,
            )
            model = fit_qfl(
                features,
                targets,
                weights,
                steps=args.steps,
                batch_size=args.batch_size,
                learning_rate=args.learning_rate,
                device=torch.device(args.device),
                seed=args.seed + fold,
            )
            np.savez_compressed(
                model_path,
                **{key: np.asarray(value) for key, value in model.items()},
            )
        quality_logits = predict_qfl(validation_designs, model)
        training_quality_logits = predict_qfl(training_designs, model)
        quality_rank_references = fit_classwise_ecdf(
            training_videos, training_quality_logits, num_classes
        )
        learned_ranks = apply_classwise_ecdf(
            validation_videos, quality_logits, quality_rank_references
        )
        original_ranks = apply_classwise_ecdf(
            validation_videos,
            [video["scores"] for video in validation_videos],
            raw_rank_references,
        )
        geometric_scores = geometric_quality_scores(
            validation_videos, quality_logits
        )
        variants = [
            ("qfl_rank", learned_ranks, 0.0),
            (
                "qfl_rank_blend50",
                [
                    0.5 * learned + 0.5 * original
                    for learned, original in zip(
                        learned_ranks, original_ranks
                    )
                ],
                0.0,
            ),
            (
                "qfl_geometric",
                geometric_scores,
                0.0,
            ),
            ("qfl_rank_blend50_voting07", [
                0.5 * learned + 0.5 * original
                for learned, original in zip(
                    learned_ranks, original_ranks
                )
            ], 0.7),
        ]
        for threshold in (0.50, 0.70, 0.90):
            variants.append(
                (
                    f"qfl_geometric_voting{threshold:g}",
                    geometric_scores,
                    threshold,
                )
            )
        annotation_path = (
            args.annotation_root
            / f"thumos14_10classes_transfer_fold{fold}.json"
        )
        for name, scores, voting_threshold in variants:
            metrics = evaluate_variant(
                videos=validation_videos,
                scores=scores,
                annotation_path=annotation_path,
                split=f"transfer_val_{fold}",
                evaluator_class=ANETdetection,
                batched_nms=batched_nms,
                segment_voting=seg_voting,
                nms_method="soft",
                sigma=0.5,
                voting_threshold=voting_threshold,
                prediction_path=(
                    args.output_dir
                    / "predictions"
                    / f"fold_{fold}_{name}.npz"
                ),
            )
            rows.append(
                {
                    "fold": fold,
                    "variant": name,
                    "nms_method": "soft",
                    "sigma": 0.5,
                    "voting_threshold": voting_threshold,
                    **metrics,
                }
            )
            print(
                f"fold={fold} variant={name} "
                f"mAP={metrics['mAP']:.6f} AP@0.7={metrics['AP@0.7']:.6f}"
            )
        del training_designs
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    write_csv(args.output_dir / "fold_metrics.csv", rows)
    # Add an external baseline row before calling the shared gate summary.
    baseline_metrics = []
    for fold, validation_videos in enumerate(all_folds):
        annotation_path = (
            args.annotation_root
            / f"thumos14_10classes_transfer_fold{fold}.json"
        )
        metrics = evaluate_variant(
            videos=validation_videos,
            scores=[video["scores"] for video in validation_videos],
            annotation_path=annotation_path,
            split=f"transfer_val_{fold}",
            evaluator_class=ANETdetection,
            batched_nms=batched_nms,
            segment_voting=seg_voting,
            nms_method="soft",
            sigma=0.5,
            voting_threshold=0.0,
            prediction_path=(
                args.output_dir
                / "predictions"
                / f"fold_{fold}_official_soft05.npz"
            ),
        )
        baseline_metrics.append(
            {
                "fold": fold,
                "variant": "official_soft05",
                "nms_method": "soft",
                "sigma": 0.5,
                "voting_threshold": 0.0,
                **metrics,
            }
        )
    summary = summarize(baseline_metrics + rows)
    write_csv(args.output_dir / "summary.csv", summary)
    protocol_audit = build_protocol_audit(args.folds)
    (args.output_dir / "protocol_audit.json").write_text(
        json.dumps(protocol_audit, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(protocol_audit, indent=2))
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
